/**
 * Any icon the app can render where only "a component that draws a glyph" is
 * meant: lucide icons, the five Tabler fallbacks above, and wrappers such as
 * `codiconIcon()` (which renders a font glyph, not an SVG). Structural on
 * purpose — it is the contract, not an adapter.
 */
export type IconComponent = ComponentType<{
  className?: string
  color?: string
  size?: number | string
  strokeWidth?: number | string
  style?: CSSProperties
  'aria-hidden'?: boolean | 'true' | 'false'
}>

/**
 * Named icon-size scale — the single source of truth for SVG icon dimensions,
 * replacing ad-hoc `h-N w-N` / `size={N}`. Use `<Icon className={iconSize.sm} />`
 * (Tailwind `size-*` sets w+h and beats the icon's default 24px); compose with
 * `cn()` for colour/animation classes.
 */
export const iconSize = {
  xs: 'size-3', // 12px
  sm: 'size-3.5', // 14px
  md: 'size-4', // 16px
  lg: 'size-5', // 20px
  xl: 'size-6' // 24px
} as const

export type IconSize = keyof typeof iconSize
